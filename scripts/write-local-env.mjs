import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { ANVIL_ACCOUNT_0, LOCAL_CHAIN_ID, LOCAL_RPC_URL, PERMIT2 } from "./anvil-account.mjs";
import { repoRoot } from "./repo-env.mjs";

export function parseForgeLabels(output) {
  const labels = {};
  for (const line of output.split(/\r?\n/)) {
    const m = line.match(/\b(poolManager|permit2|positionManager|launchFactory|launchLocker|deployBlock|token|tokenId)\s*:?\s+(0x[a-fA-F0-9]{40}|\d+)\s*$/);
    if (m) labels[m[1]] = m[2];
  }
  return labels;
}

export function writeDeployment(contracts, extra = {}) {
  const root = repoRoot();
  const dir = path.join(root, "deployments");
  mkdirSync(dir, { recursive: true });
  const payload = {
    chainId: LOCAL_CHAIN_ID,
    rpcUrl: LOCAL_RPC_URL,
    contracts: {
      launchFactory: contracts.launchFactory,
      launchLocker: contracts.launchLocker,
      poolManager: contracts.poolManager,
      positionManager: contracts.positionManager,
      universalRouter: contracts.universalRouter ?? null,
      permit2: contracts.permit2 || PERMIT2,
    },
    ...extra,
  };
  const file = path.join(dir, `local-${LOCAL_CHAIN_ID}.json`);
  writeFileSync(file, `${JSON.stringify(payload, null, 2)}\n`);
  return { file, payload };
}

export function writeLocalEnv(deployment) {
  const root = repoRoot();
  const c = deployment.contracts;
  const startBlock = deployment.deployBlock ?? "0";
  const body = `# Generated by npm run contracts:deploy:local — gitignored.
# Anvil account #0 is a well-known Foundry test key. LOCAL ONLY. Never use on a public chain.

CHAIN_ID=${LOCAL_CHAIN_ID}
RPC_URL=${LOCAL_RPC_URL}
NEXT_PUBLIC_CHAIN_ID=${LOCAL_CHAIN_ID}
NEXT_PUBLIC_RPC_URL=${LOCAL_RPC_URL}
NEXT_PUBLIC_APP_URL=http://localhost:3000

LAUNCH_FACTORY_ADDRESS=${c.launchFactory}
LAUNCH_LOCKER_ADDRESS=${c.launchLocker}
LAUNCH_DEPLOY_BLOCK=${startBlock}
INDEXER_START_BLOCK=${startBlock}
INDEXER_CONFIRMATIONS=0
INDEXER_POLL_INTERVAL=2000
INDEXER_SYNC_LOOP=1

UNISWAP_POOL_MANAGER_ADDRESS=${c.poolManager}
UNISWAP_POSITION_MANAGER_ADDRESS=${c.positionManager}
UNISWAP_PERMIT2_ADDRESS=${c.permit2}

DATABASE_URL=postgres://fused:fused@127.0.0.1:5432/fused_ai

DEPLOYER_PRIVATE_KEY=${ANVIL_ACCOUNT_0.privateKey}
`;
  const file = path.join(root, ".env.local");
  writeFileSync(file, body);
  return file;
}

export function readDeployment() {
  const file = path.join(repoRoot(), "deployments", `local-${LOCAL_CHAIN_ID}.json`);
  if (!existsSync(file)) return null;
  return JSON.parse(readFileSync(file, "utf8"));
}
