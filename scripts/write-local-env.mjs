import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { ANVIL_ACCOUNT_0, LOCAL_CHAIN_ID, LOCAL_RPC_URL, PERMIT2 } from "./anvil-account.mjs";
import { parseEnvFile, repoRoot } from "./repo-env.mjs";

export function parseForgeLabels(output) {
  const labels = {};
  for (const line of output.split(/\r?\n/)) {
    const m = line.match(/\b(poolManager|permit2|positionManager|launchFactory|launchLocker|deployBlock|token|tokenId)\s*:?\s+(0x[a-fA-F0-9]{40}|\d+)\s*$/);
    if (m) labels[m[1]] = m[2];
  }
  return labels;
}

export function writeDeployment(contracts, extra = {}) {
  const root = repoRoot();
  const dir = path.join(root, "deployments");
  mkdirSync(dir, { recursive: true });
  const payload = {
    network: "local",
    chainId: LOCAL_CHAIN_ID,
    status: "DEPLOYED",
    rpcUrl: LOCAL_RPC_URL,
    contracts: {
      launchFactory: contracts.launchFactory,
      launchLocker: contracts.launchLocker,
      poolManager: contracts.poolManager,
      positionManager: contracts.positionManager,
      universalRouter: contracts.universalRouter ?? null,
      permit2: contracts.permit2 || PERMIT2,
    },
    curve: {
      virtualQuoteWei: "50000000000000000",
      virtualToken: "1000000000000000000000000000",
      graduationTargetWei: "100000000000000000",
      feeBps: 0,
      lpFee: 10000,
      note: "LOCAL TEST PARAMETERS. Not production defaults.",
    },
    ...extra,
  };
  const file = path.join(dir, `local-${LOCAL_CHAIN_ID}.json`);
  writeFileSync(file, `${JSON.stringify(payload, null, 2)}\n`);
  return { file, payload };
}

export function writeLocalEnv(deployment) {
  const root = repoRoot();
  const c = deployment.contracts;
  const startBlock = deployment.deployBlock ?? "0";
  const file = path.join(root, ".env.local");
  const existing = parseEnvFile(file);
  const generated = {
    CHAIN_ID: String(LOCAL_CHAIN_ID),
    RPC_URL: LOCAL_RPC_URL,
    NEXT_PUBLIC_CHAIN_ID: String(LOCAL_CHAIN_ID),
    NEXT_PUBLIC_RPC_URL: LOCAL_RPC_URL,
    NEXT_PUBLIC_APP_URL: existing.NEXT_PUBLIC_APP_URL || "http://localhost:3000",
    LAUNCH_FACTORY_ADDRESS: c.launchFactory,
    LAUNCH_LOCKER_ADDRESS: c.launchLocker,
    LAUNCH_DEPLOY_BLOCK: String(startBlock),
    INDEXER_START_BLOCK: String(startBlock),
    INDEXER_CONFIRMATIONS: existing.INDEXER_CONFIRMATIONS || "0",
    INDEXER_POLL_INTERVAL: existing.INDEXER_POLL_INTERVAL || "2000",
    INDEXER_SYNC_LOOP: existing.INDEXER_SYNC_LOOP || "1",
    UNISWAP_POOL_MANAGER_ADDRESS: c.poolManager,
    UNISWAP_POSITION_MANAGER_ADDRESS: c.positionManager,
    UNISWAP_PERMIT2_ADDRESS: c.permit2,
    DATABASE_URL: existing.DATABASE_URL || "postgres://fused:fused@127.0.0.1:5432/fused_ai",
    DEPLOYER_PRIVATE_KEY: existing.DEPLOYER_PRIVATE_KEY || ANVIL_ACCOUNT_0.privateKey,
    MEDIA_STORE: existing.MEDIA_STORE || "local",
    MEDIA_LOCAL_PATH: existing.MEDIA_LOCAL_PATH || ".local-data/media",
    TRACKED_ACCOUNTS_PATH: existing.TRACKED_ACCOUNTS_PATH || "config/tracked-accounts.json",
    FUSED_VIRTUAL_QUOTE_WEI: existing.FUSED_VIRTUAL_QUOTE_WEI || "50000000000000000",
    FUSED_VIRTUAL_TOKEN: existing.FUSED_VIRTUAL_TOKEN || "1000000000000000000000000000",
    FUSED_GRADUATION_TARGET_WEI: existing.FUSED_GRADUATION_TARGET_WEI || "100000000000000000",
    FUSED_FEE_BPS: existing.FUSED_FEE_BPS || "0",
    FUSED_LP_FEE: existing.FUSED_LP_FEE || "10000",
    PUBLIC_LAUNCH_ENABLED: existing.PUBLIC_LAUNCH_ENABLED || "true",
    PUBLIC_CHAIN_CONFIGURED: existing.PUBLIC_CHAIN_CONFIGURED || "false",
  };
  const merged = { ...existing, ...generated };
  const lines = [
    "# Generated by npm run contracts:deploy:local — gitignored.",
    "# Existing social/AI secrets are preserved. Anvil #0 is a Foundry test key. LOCAL ONLY.",
    "",
  ];
  for (const [key, value] of Object.entries(merged)) {
    lines.push(`${key}=${value ?? ""}`);
  }
  writeFileSync(file, `${lines.join("\n")}\n`);
  return file;
}

export function readDeployment() {
  const file = path.join(repoRoot(), "deployments", `local-${LOCAL_CHAIN_ID}.json`);
  if (!existsSync(file)) return null;
  return JSON.parse(readFileSync(file, "utf8"));
}
